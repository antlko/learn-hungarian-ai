// Package tutor is the grammar tutor: a grounded prompt around a small model.
//
// The pack teaches; the model explains; nothing the model says becomes a card.
// [R19] A small model explains Hungarian acceptably only when the material is
// in front of it, placed where it will be read, kept short, and labelled —
// see .claude/research/19-grounded-tutor.md and ADR-027.
//
// The package owns four things: the embedded reference corpus and its
// retrieval (kb.go, retrieve.go), the prompt and its budgets (prompt.go), the
// honesty check on the model's Hungarian (attest.go), and the thread store
// (store.go). It knows nothing about HTTP; internal/api wires it.
package tutor

import (
	"bufio"
	"embed"
	"fmt"
	"io/fs"
	"sort"
	"strings"
)

// The reference corpus. `src-*.md` files are generated by
// langpack/pipeline/tutor_kb.py from CC BY-SA and public-domain sources;
// `ref-*.md` files are written by hand for this app. Every file carries front
// matter naming its source and licence — see kb/LICENSES.md.
//
//go:embed kb/*.md
var kbFS embed.FS

// Section is one titled piece of the corpus — the unit of retrieval.
type Section struct {
	// ID is stable across loads: file + ordinal, for the client's source labels.
	ID    string `json:"id"`
	File  string `json:"-"`
	Title string `json:"title"`
	// Body is the section text without its heading and without the topic
	// comments; what the model is shown.
	Body   string   `json:"-"`
	Topics []string `json:"-"`
	// Source, URL and License come from the file's front matter, so an answer
	// can say where its reference came from.
	Source  string `json:"source"`
	URL     string `json:"url,omitempty"`
	License string `json:"license"`

	// lower is the search text, built once.
	lower      string
	titleLower string
}

// KB is the loaded corpus.
type KB struct {
	sections []Section
	sources  []SourceInfo
}

// SourceInfo names one origin of corpus material, for the panel's footnote.
type SourceInfo struct {
	Source  string `json:"source"`
	URL     string `json:"url,omitempty"`
	License string `json:"license"`
}

// minSectionChars drops headings that introduce nothing but sub-headings.
const minSectionChars = 60

// LoadKB parses the embedded corpus. It is called once at server start.
func LoadKB() (*KB, error) {
	return loadFrom(kbFS, "kb")
}

func loadFrom(fsys fs.FS, dir string) (*KB, error) {
	entries, err := fs.ReadDir(fsys, dir)
	if err != nil {
		return nil, fmt.Errorf("read corpus: %w", err)
	}
	kb := &KB{}
	seenSource := map[string]bool{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		raw, err := fs.ReadFile(fsys, dir+"/"+e.Name())
		if err != nil {
			return nil, err
		}
		meta, body := frontMatter(string(raw))
		secs := splitSections(e.Name(), body, meta)
		kb.sections = append(kb.sections, secs...)
		key := meta["source"] + "|" + meta["license"]
		if meta["source"] != "" && !seenSource[key] {
			seenSource[key] = true
			kb.sources = append(kb.sources, SourceInfo{
				Source: meta["source"], URL: meta["url"], License: meta["license"],
			})
		}
	}
	if len(kb.sections) == 0 {
		return nil, fmt.Errorf("the reference corpus is empty")
	}
	sort.SliceStable(kb.sources, func(i, j int) bool { return kb.sources[i].Source < kb.sources[j].Source })
	return kb, nil
}

// Sections returns every section, in file order.
func (kb *KB) Sections() []Section { return kb.sections }

// Sources lists the distinct origins of the corpus.
func (kb *KB) Sources() []SourceInfo { return kb.sources }

// frontMatter reads the `---` block at the top of a file: `key: value` lines,
// nothing fancier, because the files are ours.
func frontMatter(s string) (map[string]string, string) {
	meta := map[string]string{}
	if !strings.HasPrefix(s, "---\n") {
		return meta, s
	}
	rest := s[4:]
	end := strings.Index(rest, "\n---")
	if end < 0 {
		return meta, s
	}
	for _, line := range strings.Split(rest[:end], "\n") {
		k, v, ok := strings.Cut(line, ":")
		if !ok {
			continue
		}
		meta[strings.TrimSpace(k)] = strings.TrimSpace(v)
	}
	body := rest[end+4:]
	if i := strings.Index(body, "\n"); i >= 0 {
		body = body[i+1:]
	}
	return meta, body
}

// splitSections cuts a file at every `##`–`####` heading.
//
// A section's title is its heading chain — «Hungarian verbs › Past tense» —
// because the heading alone («Formation») says nothing out of context, and the
// chain is what the model and the source label both need. Topic tags are the
// file's default plus every `<!-- topics: … -->` comment in the chain above
// and in the section itself.
func splitSections(file, body string, meta map[string]string) []Section {
	fileTopics := splitCSV(meta["topics"])
	var out []Section
	type frame struct {
		level  int
		title  string
		topics []string
	}
	var chain []frame
	var cur *Section
	var curBody []string
	flush := func() {
		if cur == nil {
			return
		}
		text := strings.TrimSpace(strings.Join(curBody, "\n"))
		if len(text) >= minSectionChars {
			cur.Body = text
			cur.lower = strings.ToLower(text)
			cur.titleLower = strings.ToLower(cur.Title)
			out = append(out, *cur)
		}
		cur, curBody = nil, nil
	}

	sc := bufio.NewScanner(strings.NewReader(body))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	ordinal := 0
	for sc.Scan() {
		line := sc.Text()
		if level, title, ok := heading(line); ok {
			if level == 1 {
				// The document title: context for every chain, never a section.
				flush()
				chain = []frame{{level: 1, title: title}}
				continue
			}
			flush()
			for len(chain) > 0 && chain[len(chain)-1].level >= level {
				chain = chain[:len(chain)-1]
			}
			chain = append(chain, frame{level: level, title: title})
			var titles []string
			var topics []string
			topics = append(topics, fileTopics...)
			for _, f := range chain {
				if f.level > 1 {
					titles = append(titles, f.title)
				} else if f.title != "" {
					titles = append(titles, f.title)
				}
				topics = mergeTopics(topics, f.topics)
			}
			ordinal++
			cur = &Section{
				ID:      fmt.Sprintf("%s#%d", strings.TrimSuffix(file, ".md"), ordinal),
				File:    file,
				Title:   strings.Join(titles, " › "),
				Topics:  topics,
				Source:  meta["source"],
				URL:     meta["url"],
				License: meta["license"],
			}
			continue
		}
		if topics, ok := topicComment(line); ok {
			if len(chain) > 0 {
				chain[len(chain)-1].topics = mergeTopics(chain[len(chain)-1].topics, topics)
			}
			if cur != nil {
				cur.Topics = mergeTopics(cur.Topics, topics)
			}
			continue
		}
		if cur != nil {
			curBody = append(curBody, line)
		}
	}
	flush()
	return out
}

func heading(line string) (int, string, bool) {
	if !strings.HasPrefix(line, "#") {
		return 0, "", false
	}
	level := 0
	for level < len(line) && line[level] == '#' {
		level++
	}
	if level > 4 || level >= len(line) || line[level] != ' ' {
		return 0, "", false
	}
	return level, strings.TrimSpace(line[level:]), true
}

func topicComment(line string) ([]string, bool) {
	s := strings.TrimSpace(line)
	if !strings.HasPrefix(s, "<!--") || !strings.HasSuffix(s, "-->") {
		return nil, false
	}
	inner := strings.TrimSpace(strings.TrimSuffix(strings.TrimPrefix(s, "<!--"), "-->"))
	rest, ok := strings.CutPrefix(inner, "topics:")
	if !ok {
		return nil, false
	}
	return splitCSV(rest), true
}

func splitCSV(s string) []string {
	var out []string
	for _, p := range strings.Split(s, ",") {
		if p = strings.TrimSpace(p); p != "" {
			out = append(out, p)
		}
	}
	return out
}

func mergeTopics(a, b []string) []string {
	out := append([]string(nil), a...)
	for _, t := range b {
		found := false
		for _, x := range out {
			if x == t {
				found = true
				break
			}
		}
		if !found {
			out = append(out, t)
		}
	}
	return out
}
